#!/usr/bin/env node
/**
 * Regenerates the "Open source contributions" table inside README.md.
 *
 * Sources data from the GitHub Search API (PRs authored by the user, excluding
 * the user's own repositories) and rewrites the block delimited by:
 *
 *   <!-- CONTRIBUTIONS:START -->
 *   <!-- CONTRIBUTIONS:END -->
 *
 * Env vars:
 *   PROFILE_USER  GitHub login              (default: cypherbits)
 *   GH_TOKEN      Token for higher limits   (default: GITHUB_TOKEN)
 *   MIN_MERGED    Minimum merged PRs        (default: 1)
 *   MAX_ROWS      Max rows in the table     (default: 8)
 *   README        README path               (default: README.md)
 */

import { readFile, writeFile } from "node:fs/promises";

const USER = process.env.PROFILE_USER || "cypherbits";
const TOKEN = process.env.GH_TOKEN || process.env.GITHUB_TOKEN || "";
const MIN_MERGED = Number(process.env.MIN_MERGED || 1);
const MAX_ROWS = Number(process.env.MAX_ROWS || 8);
const README = process.env.README || "README.md";

const START = "<!-- CONTRIBUTIONS:START -->";
const END = "<!-- CONTRIBUTIONS:END -->";

const headers = {
  Accept: "application/vnd.github+json",
  "User-Agent": `${USER}-profile-readme`,
  "X-GitHub-Api-Version": "2022-11-28",
};
if (TOKEN) headers.Authorization = `Bearer ${TOKEN}`;

async function api(path) {
  const res = await fetch(`https://api.github.com${path}`, { headers });
  if (!res.ok) {
    throw new Error(`GET ${path} -> ${res.status} ${await res.text()}`);
  }
  return res.json();
}

/** Search API caps at 1000 results; paginate up to that. */
async function searchAll(query) {
  const items = [];
  for (let page = 1; page <= 10; page++) {
    const data = await api(
      `/search/issues?q=${encodeURIComponent(query)}&per_page=100&page=${page}&sort=created&order=desc`,
    );
    items.push(...data.items);
    if (data.items.length < 100) break;
  }
  return items;
}

function buildTable(rows) {
  const lines = [
    "| Repository | Merged | Open | What it is | Language |",
    "| --- | :---: | :---: | --- | --- |",
  ];
  for (const r of rows) {
    const name = r.repo;
    const desc = (r.description || "").replace(/\|/g, "\\|").trim();
    const short = desc.length > 90 ? `${desc.slice(0, 87)}…` : desc;
    const lang = r.language || "—";
    lines.push(
      `| [${name}](https://github.com/${name}) | ${r.merged} | ${r.open || 0} | ${short || "—"} | ${lang} |`,
    );
  }
  return lines.join("\n");
}

async function main() {
  console.log(`Collecting PRs authored by @${USER}...`);
  const prs = await searchAll(`is:pr author:${USER} -user:${USER}`);

  const byRepo = new Map();
  const bump = (repo, key) => {
    const entry = byRepo.get(repo) || { merged: 0, open: 0 };
    entry[key] += 1;
    byRepo.set(repo, entry);
  };
  for (const pr of prs) {
    const repo = pr.repository_url.split("/repos/")[1];
    if (!repo || repo.startsWith(`${USER}/`)) continue;
    if (pr.pull_request?.merged_at) bump(repo, "merged");
    else if (pr.state === "open") bump(repo, "open");
  }

  const candidates = [...byRepo.entries()]
    .filter(([, counts]) => counts.merged >= MIN_MERGED || counts.open > 0)
    .sort((a, b) => b[1].merged - a[1].merged || b[1].open - a[1].open);

  const rows = [];
  for (const [repo, counts] of candidates.slice(0, MAX_ROWS)) {
    let meta = {};
    try {
      meta = await api(`/repos/${repo}`);
    } catch (err) {
      console.warn(`Could not fetch metadata for ${repo}: ${err.message}`);
    }
    rows.push({
      repo,
      merged: counts.merged,
      open: counts.open,
      description: meta.description,
      language: meta.language,
    });
  }

  const totalMerged = [...byRepo.values()].reduce((a, b) => a + b.merged, 0);
  const table =
    rows.length === 0
      ? "_No external merged pull requests found yet._"
      : buildTable(rows);

  const block = `${START}\n<!-- Generated by .github/workflows/update-profile.yml. Do not edit by hand. -->\n\n${table}\n\n<sub>${totalMerged} merged PRs across ${byRepo.size} external repositories · last update ${new Date().toISOString().slice(0, 10)}</sub>\n${END}`;

  const readme = await readFile(README, "utf8");
  const startAt = readme.indexOf(START);
  const endAt = readme.indexOf(END);
  if (startAt === -1 || endAt === -1 || endAt < startAt) {
    throw new Error(`Markers not found in ${README}`);
  }

  const next =
    readme.slice(0, startAt) + block + readme.slice(endAt + END.length);
  await writeFile(README, next);
  console.log(
    `Updated ${README}: ${rows.length} repos shown, ${totalMerged} merged PRs total.`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
